func TestTruncationKeepsSentinelAndLimits(t *testing.T) {
	task := sampleTask()
	task.Description = strings.Repeat("é", 20000)
	task.Attachments[0].Content = strings.Repeat("λ", 20000)
	task.Progress.Attachments[0].Content = strings.Repeat("λ", 20000)
	r := Render(task, RenderOptions{})
	if len(r.Description) > maxTextBytes || len(r.Notes) > maxTextBytes {
		t.Errorf("over limits: desc=%d notes=%d", len(r.Description), len(r.Notes))
	}
	if !strings.HasSuffix(r.Notes, Sentinel+task.ID) {
		t.Error("sentinel lost after truncation")
	}
	for _, s := range []string{r.Description, r.Notes, r.Title} {
		if !isValidUTF8(s) {
			t.Error("truncation split a rune")
		}
	}
}

func isValidUTF8(s string) bool {
	for _, r := range s {
		if r == '\uFFFD' {
			return false
		}
	}
	return true
}

func TestRenderEnrichment(t *testing.T) {
	task := sampleTask()
	task.Enrichment = &model.Enrichment{
		Summary: "Differentiate twelve polynomials.", Deliverable: "PDF upload",
		Steps: []string{"Do 1-6", "Do 7-12"}, Requirements: []string{"Show work"},
		EstimateMin: ptr(90), Model: "deepseek/deepseek-v4-flash",
	}
	r := Render(task, RenderOptions{})
	for _, want := range []string{
		"Estimate: ~1.5 h\nLink:",
		"\nDifferentiate twelve polynomials.\nHand in: PDF upload\n",
		"Steps:\n1. Do 1-6\n2. Do 7-12\n",
		"Requirements:\n- Show work\n",
		"(brief generated by deepseek/deepseek-v4-flash)\n\nFrom the teacher:\nComplete problems 1-12.",
	} {
		if !strings.Contains(r.Description, want) {
			t.Errorf("description missing %q:\n%s", want, r.Description)
		}
	}
	if strings.Contains(Render(sampleTask(), RenderOptions{}).Description, "From the teacher") {
		t.Error("label should only appear with a brief")
	}
}

