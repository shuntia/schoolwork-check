func ptr[T any](v T) *T { return &v }

func sampleTask() model.Task {
	due := time.Date(2026, 9, 19, 23, 59, 0, 0, time.UTC)
	sub := time.Date(2026, 9, 18, 10, 0, 0, 0, time.UTC)
	return model.Task{
		ID: "canvas:assignment:501", Source: model.SourceCanvas, Kind: model.KindAssignment,
		Course: "AP Calculus", Title: "Problem Set 4", URL: "https://c/501",
		DueAt: &due, Points: ptr(20.0),
		Description: "Complete problems 1-12.\n- Show work",
		Attachments: []model.Attachment{{Name: "handout.pdf", URL: "https://c/f/9", Content: "Differentiate x^2"}},
		Progress: model.Progress{State: model.StateSubmitted, SubmittedAt: &sub, Grade: "18/20",
			Text: "my answers", Attachments: []model.Attachment{{Name: "ps4.pdf", URL: "https://c/f/10", Content: "1. 2x"}}},
	}
}

func TestRender(t *testing.T) {
	r := Render(sampleTask(), RenderOptions{CoursePrefix: true})

	if r.Title != "AP Calculus — Problem Set 4" {
		t.Errorf("title = %q", r.Title)
	}
	if r.State != "done" || r.ExternalID != "canvas:assignment:501" || r.URL != "https://c/501" {
		t.Errorf("state/id/url = %q %q %q", r.State, r.ExternalID, r.URL)
	}
	for _, want := range []string{"Due: Sat Sep 19 23:59\n", "Course: AP Calculus", "Kind: assignment · 20 pts", "Link: https://c/501", "Complete problems 1-12.\n- Show work", "Attachments:\n- handout.pdf (https://c/f/9)"} {
		if !strings.Contains(r.Description, want) {
			t.Errorf("description missing %q:\n%s", want, r.Description)
		}
	}
	for _, want := range []string{"Progress: submitted, grade 18/20, submitted Fri Sep 18 10:00", "Submitted text:\nmy answers", "Submitted files:\n- ps4.pdf (https://c/f/10)", "--- Your file: ps4.pdf ---\n1. 2x", "--- Handout: handout.pdf ---\nDifferentiate x^2"} {
		if !strings.Contains(r.Notes, want) {
			t.Errorf("notes missing %q:\n%s", want, r.Notes)
		}
	}
	if !strings.HasSuffix(r.Notes, "\n"+Sentinel+"canvas:assignment:501") {
		t.Errorf("notes must end with sentinel:\n%s", r.Notes)
	}
	// Student work comes before handouts.
	if strings.Index(r.Notes, "Your file") > strings.Index(r.Notes, "Handout") {
		t.Error("student work should precede handouts")
	}
}

func TestRenderMinimal(t *testing.T) {
	r := Render(model.Task{ID: "x:1", Kind: model.KindMaterial, Title: "  "}, RenderOptions{})
	if r.Title != "(untitled)" || r.State != "open" {
		t.Errorf("got %q %q", r.Title, r.State)
	}
	if !strings.HasPrefix(r.Description, "Due: none\nKind: material") {
		t.Errorf("description:\n%s", r.Description)
	}
	if r.Notes != "Progress: \n"+Sentinel+"x:1" && !strings.HasSuffix(r.Notes, Sentinel+"x:1") {
		t.Errorf("notes:\n%s", r.Notes)
	}
}

